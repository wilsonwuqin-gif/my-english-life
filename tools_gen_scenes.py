FIRST = ["酒店入住", "餐厅点餐", "机场值机与安检", "日常会议"]

# ---- 排期：每天挑「最该轮到」的场景（已等待天数 / 目标周期 最大者）----
by_name = {s[1]: s for s in SCENES}


def choose(d, last_seen, prev_cat):
    def score(s):
        overdue = (d - last_seen[s[1]]) / PERIOD[s[3]]
        if s[0] == prev_cat:              # 轻微惩罚连续同分类
            overdue -= 0.35
        return overdue
    return max(SCENES, key=score)


# 预热：先空跑 400 天，让各场景的「上次出现」自然错开，
# 否则开头会把 41 个场景全过一遍才开始重复（第 2 次要等 40 多天）
last_seen = {s[1]: -PERIOD[s[3]] for s in SCENES}
prev_cat = None
for d in range(400):
    pick = choose(d, last_seen, prev_cat)
    last_seen[pick[1]] = d
    prev_cat = pick[0]
last_seen = {k: v - 400 for k, v in last_seen.items()}   # 平移到 day 0

rounds = {s[1]: 0 for s in SCENES}
days = []
for d in range(HORIZON):
    if d < len(FIRST):
        pick = by_name[FIRST[d]]
    else:
        pick = choose(d, last_seen, days[-1]["category"] if days else None)

    cat, zh, en, tier, angles = pick
    r = rounds[zh]
    days.append({
        "day": d + 1,
        "scene_zh": zh,
        "scene_en": en,
        "category": cat,
        "tier": tier,
        "round": r + 1,                      # 这是该场景第几次出现
        "focus": angles[r % len(angles)],
    })
    last_seen[zh] = d
    rounds[zh] += 1

io.open("scenes.json", "w", encoding="utf-8").write(
    json.dumps(days, ensure_ascii=False, indent=1))

# ---- 自检 ----
from collections import defaultdict
occ = defaultdict(list)
for x in days:
    occ[x["scene_zh"]].append(x["day"])
gaps = defaultdict(list)
for name, ds in occ.items():
    tier = by_name[name][3]
    for a, b in zip(ds, ds[1:]):
        gaps[tier].append(b - a)
same_cat = sum(1 for i in range(1, len(days))
               if days[i]["category"] == days[i - 1]["category"])

print(f"共 {len(days)} 天 / {len(SCENES)} 个场景")
for t, label in (("core", "核心"), ("mid", "常用"), ("low", "常规")):
    g = gaps[t]
    n = [len(occ[s[1]]) for s in SCENES if s[3] == t]
    print(f"  {label}：出现 {min(n)}-{max(n)} 次，"
          f"间隔 {min(g)}-{max(g)} 天（目标 {PERIOD[t]}）")
print(f"  相邻两天同分类：{same_cat} / {len(days)-1}")

print("\n前 24 天：")
for x in days[:24]:
    tag = {"core": "核心", "mid": "常用", "low": "常规"}[x["tier"]]
    print(f"  第{x['day']:>3}天 [{tag}] {x['scene_zh']}"
          f" 第{x['round']}次｜{x['focus']}")

print("\n酒店入住的出现日：", occ["酒店入住"][:12])
print("餐厅点餐的出现日：", occ["餐厅点餐"][:12])
